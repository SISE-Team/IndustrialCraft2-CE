  private static void offer(CreativeModeTab.Output output, Item item) {
    if (item instanceof CreativeVariants variants)
      variants.addCreativeVariants(
          stack -> {
            if (stack == null || stack.isEmpty())
              throw new IllegalStateException("Empty creative variant: " + item);
            output.accept(stack.copyWithCount(1));
          });
    else output.accept(item);
  }

  public static void accept(Identifier tab, CreativeModeTab.Output output) {
    for (var item : Membership.TABS.getOrDefault(tab, List.of())) offer(output, item);
    if (DevelopmentMode.active() && tab.equals(CreativeTabs.TOOLS_AND_UTILITIES))
      offer(output, ItemDefinitions.DEBUG_ITEM);
    var view = dynamicView;
    for (var assignment : view) if (tab.equals(assignment.tab())) offer(output, assignment.item());
  }

  public static boolean isIn(Item item, Identifier tab) {
    if (item == null || tab == null) return false;
    if (Membership.TABS.getOrDefault(tab, List.of()).contains(item)) return true;
    for (var assignment : dynamicView)
      if (assignment.item() == item && tab.equals(assignment.tab())) return true;
    return false;
  }
