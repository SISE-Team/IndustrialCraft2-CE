  private record Assignment(Item item, Identifier tab) {}

  private static final LinkedHashMap<Item, Identifier> dynamic = new LinkedHashMap<>();
  private static volatile List<Assignment> dynamicView = List.of();

  public static synchronized void assignDynamic(Item item, Identifier tab) {
    Objects.requireNonNull(item);
    Objects.requireNonNull(tab);
    var prior = dynamic.put(item, tab);
    if (tab.equals(prior)) return;
    dynamicView =
        dynamic.entrySet().stream()
            .map(entry -> new Assignment(entry.getKey(), entry.getValue()))
            .toList();
  }

